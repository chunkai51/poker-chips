async function updateFirebaseState(options = {}) {
  if (!room.roomId) return true;
  if (batchingStateUpdate) return true;

  const {
    expectedHandId = null,
    allowedStatuses = null,
    expectedStateVersion = null,
    remoteGuard = null
  } = options;
  const guardedWrite = expectedHandId !== null ||
    expectedStateVersion !== null ||
    Array.isArray(allowedStatuses);
  const nextStateVersion = stateVersion + 1;

  const nextGameState = createGameStateSnapshot({
    currentRound,
    pot,
    currentBet,
    lastRaiseSize,
    currentPlayerIndex,
    logs: room.gameState.logs,
    inProgress: room.gameState.inProgress,
    gameOver,
    awaitingShowdown,
    pendingPots,
    selectedWinnersByPot,
    pendingDealPrompt,
    settlementPreview,
    nextHandApprovals,
    handId,
    handStatus,
    stateVersion: nextStateVersion,
    updatedBy: clientId
  });
  const preparedSync = prepareRoomDataForGameSync({
    room,
    players,
    clientId,
    nextGameState,
    normalizeRoomMode,
    getRoomHostId,
    normalizeAdminPlayerIds,
    normalizeJoinRequests,
    touchMemberWithProfile
  });
  room = preparedSync.room;
  const nextRoomData = preparedSync.roomData;

  syncWriteInProgress = true;
  setSyncStatus("同步中...");
  refreshInteractiveControls();

  try {
    if (guardedWrite) {
      const result = await transactRoom(room.roomId, (currentRoom) => {
        return buildGuardedRoomSyncPayload({
          currentRoom,
          nextRoomData,
          roomId: room.roomId,
          expectedHandId,
          expectedStateVersion,
          allowedStatuses,
          remoteGuard,
          toNonNegativeNumber,
          inferHandStatus,
          mergePlayerIdentityFields,
          normalizeRoomMode,
          getRoomHostId,
          normalizeAdminPlayerIds,
          normalizeJoinRequests,
          normalizeMembers
        });
      }, { applyLocally: false });

      if (!result.committed) {
        const refreshed = await refreshFromRemote();
        if (!refreshed) syncReady = false;
        setSyncStatus("同步被其他设备抢先更新", "error");
        return false;
      }
    } else {
      const result = await transactRoom(room.roomId, (currentRoom) => {
        return buildMergedRoomSyncPayload({
          currentRoom,
          nextRoomData,
          roomId: room.roomId,
          mergePlayerIdentityFields,
          normalizeRoomMode,
          getRoomHostId,
          normalizeAdminPlayerIds,
          normalizeJoinRequests,
          normalizeMembers
        });
      }, { applyLocally: false });

      if (!result.committed) {
        const refreshed = await refreshFromRemote();
        if (!refreshed) syncReady = false;
        setSyncStatus("同步被其他设备抢先更新", "error");
        return false;
      }
    }

    stateVersion = nextStateVersion;
    room.gameState = nextGameState;
    syncReady = true;
    setSyncStatus("已同步", "ok");
    return true;
  } catch (error) {
    const permissionDenied = String(error?.message || error).includes("permission");
    setSyncStatus(permissionDenied ? "同步失败：权限不足" : "同步失败", "error");
    const refreshed = await refreshFromRemote();
    if (!refreshed) syncReady = false;
    return false;
  } finally {
    syncWriteInProgress = false;
    refreshInteractiveControls();
  }
}

